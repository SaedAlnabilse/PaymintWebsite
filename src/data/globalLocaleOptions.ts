const getDisplayName = (type: 'region' | 'currency', code: string, locale: string, fallback: string) => {
  try {
    const DisplayNames = (globalThis as any).Intl?.DisplayNames;
    if (!DisplayNames) return fallback;
    return new DisplayNames([locale || 'en'], { type }).of(code) || fallback;
  } catch {
    return fallback;
  }
};

const normalizeLocale = (locale?: string | null) => (locale || 'en').split('-')[0] || 'en';

const sortWithPreferred = <T extends { code: string; name: string }>(items: T[], preferredCodes: readonly string[], locale: string) => {
  const preferred = new Map(preferredCodes.map((code, index) => [code, index]));
  return [...items].sort((a, b) => {
    const aPreferred = preferred.has(a.code) ? preferred.get(a.code)! : Number.POSITIVE_INFINITY;
    const bPreferred = preferred.has(b.code) ? preferred.get(b.code)! : Number.POSITIVE_INFINITY;
    if (aPreferred !== bPreferred) return aPreferred - bPreferred;
    return a.name.localeCompare(b.name, locale);
  });
};

const TIME_ZONES_BY_COUNTRY = TIME_ZONE_ROWS.reduce((acc, [code, timeZones]) => {
  acc[code] = [...timeZones];
  return acc;
}, {} as Record<string, string[]>);

export const normalizeTimeZone = (timeZone?: string | null) => {
  if (!timeZone) return null;
  try {
    new Intl.DateTimeFormat('en-US', { timeZone });
    return timeZone;
  } catch {
    return null;
  }
};

export const getDeviceTimeZone = () => {
  try {
    return normalizeTimeZone(Intl.DateTimeFormat().resolvedOptions().timeZone) || 'UTC';
  } catch {
    return 'UTC';
  }
};

export const getCountryTimeZones = (countryCode: string | null | undefined) => {
  const code = (countryCode || '').toUpperCase();
  return TIME_ZONES_BY_COUNTRY[code] || [];
};

export const getBestTimeZoneForCountry = (countryCode: string | null | undefined, preferredTimeZone?: string | null) => {
  const countryTimeZones = getCountryTimeZones(countryCode);
  const normalizedPreferred = normalizeTimeZone(preferredTimeZone);
  if (normalizedPreferred && countryTimeZones.includes(normalizedPreferred)) {
    return normalizedPreferred;
  }
  return countryTimeZones[0] || normalizedPreferred || 'UTC';
};

export const getCountryOptions = (locale?: string | null): CountryOption[] => {
  const normalizedLocale = normalizeLocale(locale);
  const options = COUNTRY_ROWS.map(([code, fallbackName, currencyCodes]) => {
    const name = getDisplayName('region', code, normalizedLocale, fallbackName);
    const currencyList = [...currencyCodes];
    const timeZoneList = getCountryTimeZones(code);
    const currencyCode = currencyList[0] || 'USD';
    const timeZone = timeZoneList[0] || 'UTC';
    return {
      code,
      name,
      currencyCode,
      currencyCodes: currencyList,
      timeZone,
      timeZones: timeZoneList,
      label: `${name} (${currencyList.join(', ')})`,
    };
  });

  return sortWithPreferred(options, PREFERRED_COUNTRY_CODES, normalizedLocale);
};

export const getCurrencyOptions = (locale?: string | null): CurrencyOption[] => {
  const normalizedLocale = normalizeLocale(locale);
  const options = CURRENCY_ROWS.map(([code, fallbackName]) => {
    const name = getDisplayName('currency', code, normalizedLocale, fallbackName);
    return {
      code,
      name,
      symbol: code,
      label: `${code} - ${name}`,
    };
  });

  return sortWithPreferred(options, PREFERRED_CURRENCY_CODES, normalizedLocale);
};

export const COUNTRY_OPTIONS = getCountryOptions('en');
export const CURRENCY_OPTIONS = getCurrencyOptions('en');
export const CURRENCIES = CURRENCY_OPTIONS;

export const getCountryName = (countryCode: string | null | undefined, locale?: string | null) => {
  const code = (countryCode || '').toUpperCase();
  return getCountryOptions(locale).find((country) => country.code === code)?.name || code;
};

export const getCurrencyName = (currencyCode: string | null | undefined, locale?: string | null) => {
  const code = (currencyCode || '').toUpperCase();
  return getCurrencyOptions(locale).find((currency) => currency.code === code)?.name || code;
};

export const getCountryPrimaryCurrency = (countryCode: string | null | undefined) => {
  const code = (countryCode || '').toUpperCase();
  return COUNTRY_OPTIONS.find((country) => country.code === code)?.currencyCode || 'USD';
};
